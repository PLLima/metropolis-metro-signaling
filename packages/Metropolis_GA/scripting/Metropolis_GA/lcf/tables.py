def setup(lcf2pis, generated_tables=None):
    pack = ProjectAPI.PackageLocation(ProjectAPI.TopPackage)
    conf = os.path.join(pack, "Prover-iLock-config")
    proj = ProjectAPI.Location
    table_file = os.path.join(proj, "config", "tables.lcf")

    try:
        # Primary tables that have been generated by earlier scripts
        if generated_tables:
            for table in generated_tables:
                lcf2pis.addPrimaryTable(table)
        # Primary tables imported from disk
        primary_tables = parse_tables(table_file)
        for table in primary_tables:
            lcf2pis.addPrimaryTable(table)
    except GeoError as e:
        UtilityAPI.LogError(
            "Object model LCF setup failed: %s" % str(e))
        sys.exit()


@typedoc
def parse_tables(path):
    """
    Parse primary LCF tables. Returns a list with primary tables.

    @param path: Path to lcf file with primary tables (in SA config).
    @type path: string
    @rtype: [Table]
    """
    if not os.path.exists(path):
        return list()
    import System
    try:
        parsed_result = LCFTableAPI.ParseTables([path])
    except System.Exception as e:
        UtilityAPI.LogError("Error when parsing tables from %s:\n%s"
                            % (path, e.ShowError))
        sys.exit()
    return [tab
            for table_struct in parsed_result
            for tab in table_struct.Tables]
